const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {loadClient} = require('./client-runtime.cjs');
const clone = value => JSON.parse(JSON.stringify(value));
const tick = () => new Promise(resolve => setImmediate(resolve));
const fixture = file => JSON.parse(fs.readFileSync(path.join(__dirname, '.runtime', file), 'utf8'));

(async () => {
  const {modules, m, app, expand} = loadClient('forum');
  const get = key => modules.get(key).default || modules.get(key);
  const State = get('forum/profile/ProfileState'), Panel = get('forum/profile/ProfilePanel');
  const view = fixture('development-view.json'), commands = [];
  const api = {read: async () => clone(view), progress: async (id, body) => {commands.push(clone(body)); return clone(view);}};
  const state = new State(api, () => {}, () => 'cccccccc-cccc-4ccc-8ccc-cccccccccccc');
  await state.select(view.snapshot.character.id);
  const panel = new Panel();
  panel.oninit(m(Panel, {state}));
  let nodes = expand(panel.view());
  assert.ok(!nodes.some(node => node.tag === 'button' && JSON.stringify(node.children).includes('Повысить ·')), 'No upgrade button before selection');
  const attribute = nodes.find(node => node.tag === 'div' && node.attrs.role === 'button' && node.attrs.onclick);
  assert.ok(attribute, 'Available attribute is selectable');
  attribute.attrs.onclick();
  nodes = expand(panel.view());
  const confirm = nodes.find(node => node.tag === 'button' && JSON.stringify(node.children).includes('Повысить ·'));
  assert.ok(confirm, 'Selection shows price and confirmation');
  await confirm.attrs.onclick();
  assert.equal(commands[0].kind, 'attribute');
  assert.equal(commands[0].revision, view.snapshot.character.revision);
  assert.ok(!('cost' in commands[0]), 'Client never dictates cost');
  const conflict = new State({...api, progress: async () => {throw {status: 409};}}, () => {});
  await conflict.select(view.snapshot.character.id);
  await conflict.develop('attribute', Number(view.development.attributes.find(row => row.allowed).id));
  assert.equal(conflict.view.development, null, 'Conflict revokes stale development controls');
  state.view = fixture('management-view.json');
  app.result = fixture('management-lookups.json');
  const Modal = get('forum/profile/CharacterManagementModal');
  const modal = new Modal();
  modal.oninit(m(Modal, {profile: state, state: {modalManager: true}}));
  await tick();
  nodes = expand(modal.view());
  assert.ok(nodes.some(node => node.tag === 'textarea' && node.attrs.required), 'Grant requires reason');
  assert.equal(modal.category, 'resources', 'Resources are shown first');
  nodes = expand(modal.view());
  assert.ok(nodes.some(node => node.tag === 'input' && node.attrs.type === 'number'), 'Balances use numeric input');
  modal.category = 'perk';
  modal.sourceId = app.result.lookups.sources.find(row => row.name_source === 'race').id;
  expand(modal.view()); // Real Mithril rejects mixed keys, including conditional selectors.
  console.log('Gameplay UI: selection, confirmation, versions, private permissions and moderator forms passed.');
})().catch(error => {console.error(error); process.exit(1);});
