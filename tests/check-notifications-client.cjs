const assert=require('node:assert/strict'),{loadClient}=require('./client-runtime.cjs');
const {modules,app,m}=loadClient('forum');
const Module=modules.get('forum/notifications/CharacterNotification'),Notification=Module.default||Module;
assert.deepEqual(Object.keys(app.notificationComponents).sort(),['roleplayGrants','roleplayRank','roleplayReview']);
assert.ok(app.store.models['roleplay-events']);
const data={kind:'reward',characterId:15,eventId:91,characterName:'<Риан>',experience:25,gold:10};
const instance=new Notification();instance.oninit(m(Notification,{notification:{content:()=>data}}));
assert.equal(instance.href(),'/u/player/roleplay?character=15&event=91');
let translation;
app.translator.trans=(key,args)=>{translation={key,args};return key;};
instance.content();
assert.equal(translation.key,'maxcuso-roleplay.forum.notifications.reward');
assert.equal(translation.args.character.tag,'strong');
assert.equal(translation.args.character.children[0].children,'<Риан>','Name stays text rather than trusted HTML');
data.kind='literature_approved';data.discussionId=42;data.postNumber=8;
assert.equal(instance.href(),'/api/d/42/8');
data.kind='activated';assert.equal(instance.href(),'/u/player/roleplay?character=15&event=91');
data.kind='episode_reward';data.name='Переправа';instance.content();
assert.equal(translation.key,'maxcuso-roleplay.forum.notifications.episode_reward');
assert.equal(instance.href(),'/u/player/roleplay?character=15&event=91');
assert.equal(instance.excerpt(),null);
console.log('Native notifications: registration, existing model store, exact links, escaped content passed');
