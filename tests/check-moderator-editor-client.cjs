const assert = require('node:assert/strict');
const {loadClient} = require('./client-runtime.cjs');
const {modules, app, m, expand, initializers} = loadClient('forum');
const exported = name => modules.get(name).default || modules.get(name);
const {moderatorMenu, moderatorContext: context} = modules.get('forum/episodes/ModeratorTools');
const permissions = {canCreateQuestEvents: true, canCreateForumEvents: true, canManageQuestEvents: false, roleplayCanUseWorkspace: false,
  questEventsRoleplayAvailable: true, questEventsQuestsEnabled: true};
app.forum.attribute = key => permissions[key];
const discussionFields = {canLock: true, roleplayCanCompleteEpisode: true};
const discussion = {attribute: key => discussionFields[key], id: () => '12'};
let reply = true, inserted;
const driver = {getSelectionRange: () => [7, 10], insertBetween: (...args) => {inserted = args;}};
const composer = {body: {attrs: {discussion}}, editor: driver, bodyMatches: () => reply};
let nodes = expand(moderatorMenu(composer));
assert.ok(nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Модератор' && node.attrs['data-toggle'] === 'dropdown'));
assert.ok(nodes.some(node => node.tag === 'ul' && node.attrs.role === 'menu' && node.attrs.popover === 'manual'), 'Menu escapes the clipping toolbar through the browser top layer');
assert.ok(!nodes.some(node => node.attrs?.role === 'tab'), 'Moderator tools add no editor tabs');
assert.ok(nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Завершение эпизода' && !node.attrs.disabled));
assert.ok(!nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Создание события'), 'Events are outside the moderator panel');
assert.equal(nodes.filter(node => node.tag === 'button').length, 2, 'Only the moderator toggle and one action icon are rendered');
assert.equal(inserted, undefined, 'Opening the action menu inserts or publishes nothing');
const Menu = exported('forum/episodes/ModeratorMenu');
const menuInstance = new Menu();
menuInstance.oninit(m(Menu, {composer, context: context(composer)}));
let closedByToggle = false, stopped = false, prevented = false;
menuInstance.showing = true;
menuInstance.element = {querySelector: () => ({click: () => {closedByToggle = true;}})};
menuInstance.getButton().attrs.onkeydown({key: 'Escape', preventDefault() {prevented = true;}, stopPropagation() {stopped = true;}});
assert.ok(closedByToggle && stopped && prevented, 'Escape closes the menu through the native toggle without reaching the composer');

// Checks extend the existing moderator menu, without creating another dropdown.
composer.bodyMatches = name => reply && name === 'flarum/forum/components/ReplyComposer';
app.data.resources[0].attributes.roleplayChecksAvailable = true;
initializers.get('maxcuso-roleplay-checks')();
nodes = expand(moderatorMenu(composer));
assert.ok(nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Запрос проверки' && !node.attrs.disabled));
assert.ok(!nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Бросок проверки'), 'Standalone roll belongs to the toolbar, not the moderator menu');
assert.equal(nodes.filter(node => node.tag === 'ul' && node.attrs.role === 'menu').length, 1);
assert.ok(expand(moderatorMenu(composer, true)).filter(node => node.tag === 'button').every(node => node.attrs.disabled), 'Disabled editor disables the request action too');
composer.bodyMatches = name => name === 'flarum/forum/components/EditPostComposer';
assert.ok(!expand(moderatorMenu(composer)).some(node => node.attrs?.['aria-label'] === 'Запрос проверки'), 'Editing an existing post offers no new request');
composer.bodyMatches = name => reply && name === 'flarum/forum/components/ReplyComposer';

discussionFields.roleplayCanCompleteEpisode = false;
assert.ok(context(composer).reason.includes('активном эпизоде'));
nodes = expand(moderatorMenu(composer));
assert.ok(nodes.some(node => node.tag === 'button' && node.attrs['aria-label'] === 'Завершение эпизода' && node.attrs.disabled));
assert.ok(nodes.some(node => node.tag === 'span' && node.attrs.title?.includes('активном эпизоде')));
discussionFields.isLocked = true;
assert.equal(context(composer).reason, 'Эта тема уже закрыта');
delete discussionFields.isLocked;
reply = false;
assert.ok(context(composer).reason.includes('новым сообщением'));
composer.body = {attrs: {}};
assert.ok(context(composer).reason.includes('Откройте тему'));
permissions.canCreateQuestEvents = false;
assert.equal(context(composer).visible, false);
assert.equal(moderatorMenu(composer), null, 'Ordinary event creators receive no moderator toolbar button');

// The actual form still inserts at the saved caret and rejects a changed editor.
permissions.canCreateQuestEvents = true;
const CreateButton = exported('forum/events/components/EventCreateButton');
const button = new CreateButton();
button.oninit(m(CreateButton, {composer}));
assert.equal(button.view().attrs['aria-label'], 'Создание события');
assert.ok(button.view().attrs.className.includes('Button--icon'));
button.view().attrs.onclick();
const modal = app.lastModal;
assert.equal(modal.ModalClass, exported('forum/events/components/EventCreateModal'));
modal.attrs.oninsert('[quest title="Проверка"][/quest]');
assert.deepEqual(inserted, [7, 7, '\n[quest title="Проверка"][/quest]\n', true]);
composer.body = {attrs: {}};
assert.throws(() => modal.attrs.oninsert('wrong editor'), /Редактор изменился/);
const Form = exported('forum/events/components/EventForm');
const form = new Form(); let code, closed = false;
form.oninit(m(Form, {oninsert: value => {code = value;}, oncancel: () => {closed = true;}}));
nodes = expand(form.view());
assert.ok(!nodes.some(node => String(node.attrs?.className || node.tag).includes('Dropdown-menu')));
form.values.title = 'Поход через перевал';
form.insert({preventDefault() {}, stopPropagation() {}});
assert.ok(code?.startsWith('[quest ')); assert.equal(closed, true);
console.log('Moderator toolbar passed: shared request menu, independent rolls, no editor tabs, permissions, unavailable reasons and safe modal insertion');
